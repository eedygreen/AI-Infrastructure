    def _create_comparison_result(self, comparison_results: Dict) -> None:
        """ Create summary comparison across different configurations.
        
        Args:
            comparison_results (Dict): Results from compare_configurations
        """

        results = comparison_results['results']
        overall_score = {config: result["overall_score"] for config, result in results.items()}
        best_config = max(overall_score.items(), key=lambda x: x[1])

        comparison_results["summary"] = {
            "best_overall": best_config, 
            "score_comparison": overall_score,
            "evaluation time": {config: result['evaluation_time'] for config, result in results.items()}
        }

        print(f"\n📊 CONFIGURATION COMPARISON SUMMARY:")
        print(f"   Best Overall Performance: {best_config[0]} ({best_config[1]:.4f})")
        
        print(f"\n   Score Comparison:")
        for config, score in sorted(overall_score.items(), key=lambda x: x[1], reverse=True):
            print(f"     {config}: {score:.4f}")
    
